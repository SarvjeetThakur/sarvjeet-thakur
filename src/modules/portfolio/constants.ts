/**
 * Absolute origin of the deployed site.
 *
 * `metadataBase`, the canonical URL, the sitemap, robots and the OG image URL
 * all need an absolute origin, and Next makes a relative OG image a *build
 * error* when `metadataBase` is unset. Set `NEXT_PUBLIC_SITE_URL` in the
 * deploy environment; the fallback is only right for local development, and
 * shipping with it unset means the canonical points at localhost.
 */
const VERCEL_URL = process.env.NEXT_PUBLIC_VERCEL_PROJECT_PRODUCTION_URL;

export const SITE_URL =
  process.env.NEXT_PUBLIC_SITE_URL ??
  // Vercel exposes the production domain (no protocol) automatically, so a
  // deploy that forgets the variable above still gets a correct canonical
  // rather than one pointing at localhost. A custom domain still needs it.
  (VERCEL_URL ? `https://${VERCEL_URL}` : "http://localhost:3000");

/** Open Graph image, generated by src/app/opengraph-image.tsx. */
export const OG_IMAGE_SIZE = { width: 1200, height: 630 };
/** Apple touch icon, generated by src/app/apple-icon.tsx. */
export const APPLE_ICON_SIZE = { width: 180, height: 180 };
