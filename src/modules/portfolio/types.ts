import type { PresenceLabels } from "@/modules/presence";
import type { IconName } from "@/modules/shared";

export type SectionCopy = { index: string; heading: string };

export type NavLink = {
  id: string;
  label: string;
  /** Dropped from the nav on small screens, where five pills do not fit. */
  minor?: boolean;
};

export type HeroAction = {
  label: string;
  href: string;
  icon: IconName;
  /** Filled accent button, as opposed to the outlined one. */
  primary: boolean;
};

export type SiteContent = {
  name: string;
  initials: string;
  role: string;
  language: string;
  /** Single source of truth for anything that counts years. */
  career: { startDate: string };
  location: { locality: string; region: string; country: string };
  meta: { title: string; description: string; ogAlt: string };
  hero: {
    greeting: string;
    /** One line per array entry. */
    headline: string[];
    intro: string;
    actions: HeroAction[];
    /** One line telling a first-time reader physics mode exists. */
    physicsNote: string;
    stats: { value: string; label: string }[];
  };
  nav: { label: string; links: NavLink[]; skip: string; mainLabel: string };
  sections: {
    work: SectionCopy;
    stack: SectionCopy;
    about: SectionCopy;
    resume: SectionCopy;
    contact: SectionCopy;
  };
  physics: {
    enter: string;
    exit: string;
    overview: string;
    shake: string;
    reset: string;
    zoomIn: string;
    zoomOut: string;
    panUp: string;
    panDown: string;
    hint: string;
    toolbarLabel: string;
    /** Announced in a live region when the mode changes. */
    entered: string;
    exited: string;
  };
  presence: PresenceLabels;
  theme: { label: string; light: string; dark: string };
  footer: { backToTop: string };
};

export type ContentImage = {
  src: string;
  alt: string;
  width: number;
  height: number;
};

export type Project = {
  slug: string;
  title: string;
  summary: string;
  /** Industry, not a year: the badge says what kind of product this was. */
  domain: string;
  role: string;
  /**
   * Absent where there is nothing appropriate to link: the government systems
   * are not public, and a staging or login-walled URL is not a portfolio link.
   */
  href?: string;
  /** Featured projects get a full-width row; the rest sit in the grid. */
  featured: boolean;
  tags: string[];
  metric: { value: string; label: string };
  image: ContentImage;
};

export type Tech = { label: string; icon: IconName };

export type StackGroup = {
  label: string;
  icon: IconName;
  /** Counts toward `knowsAbout`; process and tooling do not. */
  technologies: boolean;
  items: Tech[];
};

export type StackContent = { lead: string; groups: StackGroup[] };

export type Domain = { icon: IconName; label: string; text: string };

export type AboutContent = {
  lead: string;
  paragraphs: string[];
  /** Optional: the section reflows without it rather than leaving a hole. */
  portrait?: ContentImage;
  domainsHeading: string;
  domains: Domain[];
};

export type ResumeRole = {
  role: string;
  company: string;
  period: string;
  location: string;
  bullets: string[];
};

export type ResumeContent = {
  summary: string;
  /** Distinct from the home page's, so the two URLs do not compete. */
  metaTitle: string;
  metaDescription: string;
  backLabel: string;
  summaryHeading: string;
  projectsHeading: string;
  skillsHeading: string;
  /** Opens the résumé as a document on its own route. */
  viewLabel: string;
  viewHref: string;
  downloadLabel: string;
  /**
   * Path under /public. Generated by printing `/resume`, so it carries the
   * same content as the page and none of the URLs that are deliberately kept
   * off this site. Optional: the section is complete without it, which is
   * what keeps a missing file from breaking the page.
   */
  pdf?: string;
  experienceHeading: string;
  experience: ResumeRole[];
  strengthsHeading: string;
  strengths: Domain[];
};

export type ContactLink = {
  label: string;
  value: string;
  href: string;
  icon: IconName;
};

export type ContactContent = {
  lead: string;
  body: string;
  email: { label: string; href: string; icon: IconName };
  links: ContactLink[];
};
